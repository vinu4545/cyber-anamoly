import io
from typing import Dict, Any, List
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, HRFlowable

def generate_pdf_report(session_data: Dict[str, Any], top_records: List[Dict[str, Any]]) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()
    
    # Custom SOC Brand Styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#05080F")
    )
    subtitle_style = ParagraphStyle(
        "DocSub",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#5B6B80")
    )
    section_heading = ParagraphStyle(
        "SecHead",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#0D1420"),
        spaceBefore=14,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#172334")
    )
    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#5B6B80")
    )

    story = []

    # 1. Header Banner
    story.append(Paragraph("SENTINEL AI — THREAT INVESTIGATION & ANOMALY REPORT", title_style))
    story.append(Paragraph("Intelligent Network Flow Security Analysis | Generated by Unsupervised ML Engine", subtitle_style))
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#00D5FF"), spaceBefore=2, spaceAfter=12))

    # 2. Executive Metadata Box
    metrics = session_data.get("evaluation_metrics") or {}
    meta_data = [
        [
            Paragraph("<b>Session ID:</b> " + str(session_data.get("session_id", "N/A")), body_style),
            Paragraph("<b>File Name:</b> " + str(session_data.get("file_name", "N/A")), body_style)
        ],
        [
            Paragraph("<b>Execution Time:</b> " + str(session_data.get("created_at", "N/A")), body_style),
            Paragraph("<b>Algorithm:</b> Isolation Forest (contamination=" + str(session_data.get("contamination", "0.04")) + ")", body_style)
        ],
        [
            Paragraph("<b>Data Classification:</b> " + ("DEMO SAMPLE" if session_data.get("data_mode") == "demo" else "USER UPLOAD"), body_style),
            Paragraph("<b>Features Utilised:</b> " + str(session_data.get("feature_count", "N/A")) + " numeric flow metrics", body_style)
        ]
    ]
    t_meta = Table(meta_data, colWidths=[270, 270])
    t_meta.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F4F7FC")),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#CBD5E1")),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor("#E2E8F0")),
        ('PADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(t_meta)
    story.append(Spacer(1, 10))

    # 3. Key Performance Indicators
    story.append(Paragraph("EXECUTIVE FLOW METRICS", section_heading))
    kpi_data = [
        ["Total Flows", "Normal Traffic", "Flagged Anomalies", "Anomaly Rate", "Duration"],
        [
            f"{session_data.get('dataset_size', 0):,}",
            f"{session_data.get('normal_count', 0):,}",
            f"{session_data.get('anomaly_count', 0):,}",
            f"{session_data.get('anomaly_rate', 0.0):.2f}%",
            f"{session_data.get('duration_seconds', 0.0):.2f}s"
        ]
    ]
    t_kpi = Table(kpi_data, colWidths=[108]*5)
    t_kpi.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#0D1420")),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,0), 9),
        ('ALIGN', (0,0), (-1,-1), 'CENTER'),
        ('BACKGROUND', (0,1), (-1,1), colors.HexColor("#FFFFFF")),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E1")),
        ('PADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(t_kpi)

    # 4. Evaluation Metrics (if available)
    if metrics:
        story.append(Paragraph("GROUND-TRUTH MODEL EVALUATION (HELD-OUT VALIDATION)", section_heading))
        eval_data = [
            ["Metric", "Value", "Metric", "Value"],
            ["Precision", f"{metrics.get('precision', 0):.4f}", "Recall (Detection Rate)", f"{metrics.get('recall', 0):.4f}"],
            ["F1-Score", f"{metrics.get('f1_score', 0):.4f}", "False Positive Rate (FPR)", f"{metrics.get('false_positive_rate', 0):.4f}"],
            ["ROC-AUC", f"{metrics.get('roc_auc', 0):.4f}", "PR-AUC", f"{metrics.get('pr_auc', 0):.4f}"],
        ]
        t_eval = Table(eval_data, colWidths=[160, 110, 160, 110])
        t_eval.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#172334")),
            ('TEXTCOLOR', (0,0), (-1,0), colors.white),
            ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E1")),
            ('PADDING', (0,0), (-1,-1), 5),
            ('FONTSIZE', (0,0), (-1,-1), 8.5),
        ]))
        story.append(t_eval)

    # 5. Top Flagged Anomalies Table
    story.append(Paragraph("TOP SUSPICIOUS FLOWS FLAGGED FOR INVESTIGATION", section_heading))
    records_header = ["Record ID", "Source IP", "Dest IP:Port", "Proto", "Score", "Pred", "Ground Truth"]
    records_rows = [records_header]
    for r in top_records[:15]:
        dest_str = f"{r.get('destination_ip', 'N/A')}:{r.get('destination_port', '')}"
        records_rows.append([
            str(r.get('record_id', '')),
            str(r.get('source_ip') or 'N/A'),
            dest_str,
            str(r.get('protocol', 'TCP')),
            f"{float(r.get('anomaly_score', 0.0)):.2f}",
            str(r.get('prediction', 'ANOMALOUS')),
            str(r.get('ground_truth_label') or 'Unlabeled')
        ])

    t_recs = Table(records_rows, colWidths=[65, 85, 125, 45, 55, 75, 90])
    t_recs.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#05080F")),
        ('TEXTCOLOR', (0,0), (-1,0), colors.HexColor("#00D5FF")),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 8),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#E2E8F0")),
        ('PADDING', (0,0), (-1,-1), 4),
        ('ALIGN', (3,0), (4,-1), 'CENTER'),
    ]))
    story.append(t_recs)

    # 6. Integrity & Compliance Disclaimers
    story.append(Spacer(1, 14))
    story.append(Paragraph("<b>INTEGRITY & ARCHITECTURAL DISCLAIMERS:</b>", disclaimer_style))
    story.append(Paragraph(
        "1. <b>Zero Label Leakage:</b> The ground-truth Label column is strictly segregated prior to preprocessing, scaling, and training. It is accessed solely for post-inference benchmarking.<br/>"
        "2. <b>Anomaly vs Attack:</b> Unsupervised Isolation Forest isolates atypical vector spaces in network-flow dynamics. Anomalies are flagged for investigation, not classified as malicious.<br/>"
        "3. <b>Contextual Explainability:</b> Feature deviations reflect robust z-score discrepancies against normal baseline medians and do not reconstruct exact isolation tree split branches.",
        disclaimer_style
    ))

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
