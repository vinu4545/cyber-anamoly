import React, { useState, useEffect, useRef } from "react";
import {
  Play,
  Pause,
  AlertTriangle,
  Radio,
  Filter,
  ArrowDown,
  Layers,
  ShieldAlert,
  CheckCircle,
  Activity,
} from "lucide-react";
import { useSentinelStore } from "../../store/useSentinelStore";
import { api, RecordItem } from "../../lib/api";
import { Sparkline } from "../../components/common/Sparkline";

interface LogEvent {
  id: string;
  timestamp: string;
  sourceIp: string;
  destIp: string;
  port: number;
  protocol: string;
  severity: "NORMAL" | "SUSPICIOUS" | "CRITICAL";
  score: number;
  message: string;
  recordItem?: RecordItem;
}

export const LiveMonitorPage: React.FC = () => {
  const { openDrawerWithRecord } = useSentinelStore();

  const [isMonitoring, setIsMonitoring] = useState(true);
  const [filter, setFilter] = useState<string>("ALL");
  const [events, setEvents] = useState<LogEvent[]>([]);
  const [eventsPerSec, setEventsPerSec] = useState<number[]>([14, 18, 22, 19, 25, 30, 28, 35]);
  const [severityCounts, setSeverityCounts] = useState({
    normal: 142,
    suspicious: 18,
    critical: 7,
  });

  const streamEndRef = useRef<HTMLDivElement>(null);
  const [autoScroll, setAutoScroll] = useState(true);

  // Generate stream of scored flow events
  useEffect(() => {
    if (!isMonitoring) return;

    const interval = setInterval(() => {
      const now = new Date();
      const timeStr = now.toTimeString().split(" ")[0];

      // Probabilistic anomaly distribution matching typical traffic
      const rand = Math.random();
      let severity: "NORMAL" | "SUSPICIOUS" | "CRITICAL" = "NORMAL";
      let score = 0.15 + Math.random() * 0.25;
      let port = [80, 443, 53, 8080][Math.floor(Math.random() * 4)];
      let msg = "Standard TLS handshake completed.";

      if (rand > 0.88) {
        severity = "CRITICAL";
        score = 0.82 + Math.random() * 0.15;
        port = 21;
        msg = "High-frequency credential brute-force attempt detected (FTP-Patator signature).";
      } else if (rand > 0.72) {
        severity = "SUSPICIOUS";
        score = 0.58 + Math.random() * 0.2;
        port = 22;
        msg = "Atypical packet burst rate observed exceeding normal baseline threshold.";
      }

      const clientIp = `192.168.10.${Math.floor(Math.random() * 30) + 10}`;
      const serverIp = port === 21 ? "192.168.10.50" : port === 22 ? "192.168.10.51" : "104.21.35.12";

      const newEvent: LogEvent = {
        id: `LOG-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
        timestamp: timeStr,
        sourceIp: clientIp,
        destIp: serverIp,
        port,
        protocol: port === 53 ? "UDP" : "TCP",
        severity,
        score,
        message: msg,
        recordItem: {
          record_id: `LIVE-${Date.now().toString().slice(-5)}`,
          source_ip: clientIp,
          destination_ip: serverIp,
          destination_port: port,
          protocol: port === 53 ? "UDP" : "TCP",
          timestamp: timeStr,
          anomaly_score: score,
          prediction: severity === "NORMAL" ? "NORMAL" : "ANOMALOUS",
          ground_truth_label: severity === "CRITICAL" ? "FTP-Patator" : severity === "SUSPICIOUS" ? "SSH-Patator" : "BENIGN",
        },
      };

      setEvents((prev) => [...prev.slice(-120), newEvent]);

      setSeverityCounts((prev) => ({
        normal: prev.normal + (severity === "NORMAL" ? 1 : 0),
        suspicious: prev.suspicious + (severity === "SUSPICIOUS" ? 1 : 0),
        critical: prev.critical + (severity === "CRITICAL" ? 1 : 0),
      }));

      setEventsPerSec((prev) => [...prev.slice(-12), Math.floor(Math.random() * 15) + 20]);
    }, 1200);

    return () => clearInterval(interval);
  }, [isMonitoring]);

  useEffect(() => {
    if (autoScroll && streamEndRef.current) {
      streamEndRef.current.scrollIntoView({ behavior: "smooth" });
    }
  }, [events, autoScroll]);

  const filteredEvents = events.filter((e) => {
    if (filter === "NORMAL") return e.severity === "NORMAL";
    if (filter === "SUSPICIOUS") return e.severity === "SUSPICIOUS";
    if (filter === "CRITICAL") return e.severity === "CRITICAL";
    return true;
  });

  return (
    <div className="space-y-6 pb-12">
      {/* Permanent Simulation Banner */}
      <div className="p-4 rounded-2xl bg-[#FFB547]/10 border border-[#FFB547]/30 flex items-center justify-between">
        <div className="flex items-center gap-3">
          <AlertTriangle className="text-[#FFB547] shrink-0" size={20} />
          <div>
            <span className="text-xs font-mono font-bold text-[#FFB547] uppercase tracking-wide">
              SIMULATED TELEMETRY FEED
            </span>
            <p className="text-xs text-[#8795A9]">
              Events are generated by feeding sampled flow vectors into the live Isolation Forest model. This console is not currently attached to a live packet capture TAP.
            </p>
          </div>
        </div>

        <button
          onClick={() => setIsMonitoring(!isMonitoring)}
          className={`flex items-center gap-2 px-4 py-2 rounded-xl text-xs font-bold transition-all ${
            isMonitoring
              ? "bg-[#FF4567]/15 text-[#FF4567] border border-[#FF4567]/30 hover:bg-[#FF4567]/25"
              : "bg-[#19D995]/15 text-[#19D995] border border-[#19D995]/30 hover:bg-[#19D995]/25"
          }`}
        >
          {isMonitoring ? <Pause size={14} /> : <Play size={14} />}
          <span>{isMonitoring ? "PAUSE STREAM" : "RESUME STREAM"}</span>
        </button>
      </div>

      {/* Main Grid: Stream on Left, Analytics on Right */}
      <div className="grid grid-cols-1 lg:grid-cols-4 gap-6">
        {/* Left 3 Cols: Real-time Terminal Log Stream */}
        <div className="lg:col-span-3 rounded-2xl glass-panel flex flex-col h-[650px] overflow-hidden border border-[#94AFD7]/15">
          {/* Stream Controls Bar */}
          <div className="p-4 border-b border-[#94AFD7]/10 bg-[#111B29]/80 flex flex-wrap items-center justify-between gap-3">
            <div className="flex items-center gap-2">
              <span className="w-2.5 h-2.5 rounded-full bg-[#19D995] animate-pulse" />
              <span className="font-display font-bold text-sm text-[#F4F7FC]">
                Live Flow Inspection Feed
              </span>
              <span className="text-xs font-mono text-[#5B6B80]">
                ({filteredEvents.length} events buffered)
              </span>
            </div>

            {/* Severity Filter Buttons */}
            <div className="flex max-w-full flex-wrap items-center justify-end gap-1.5 text-xs font-mono">
              {["ALL", "NORMAL", "SUSPICIOUS", "CRITICAL"].map((f) => (
                <button
                  key={f}
                  onClick={() => setFilter(f)}
                  className={`px-2.5 py-1 rounded-lg border transition-all ${
                    filter === f
                      ? "bg-[#00D5FF]/15 text-[#00D5FF] border-[#00D5FF]/40 font-semibold"
                      : "bg-[#05080F]/50 text-[#8795A9] border-[#94AFD7]/10 hover:text-[#F4F7FC]"
                  }`}
                >
                  {f}
                </button>
              ))}
            </div>
          </div>

          {/* Log Stream Content */}
          <div
            className="flex-1 overflow-y-auto p-4 space-y-2 font-mono text-xs select-text bg-[#05080F]/80"
            onMouseEnter={() => setAutoScroll(false)}
            onMouseLeave={() => setAutoScroll(true)}
          >
            {filteredEvents.length === 0 ? (
              <div className="p-8 text-center text-[#5B6B80]">
                No events matching filter "{filter}". Waiting for incoming flows...
              </div>
            ) : (
              filteredEvents.map((ev) => (
                <div
                  key={ev.id}
                  onClick={() => ev.recordItem && openDrawerWithRecord(ev.recordItem)}
                  className={`p-2.5 rounded-xl border flex flex-col sm:flex-row sm:items-center justify-between gap-2 cursor-pointer transition-colors ${
                    ev.severity === "CRITICAL"
                      ? "bg-[#FF4567]/10 border-[#FF4567]/30 hover:bg-[#FF4567]/15 text-[#FF4567]"
                      : ev.severity === "SUSPICIOUS"
                      ? "bg-[#FFB547]/10 border-[#FFB547]/30 hover:bg-[#FFB547]/15 text-[#FFB547]"
                      : "bg-[#111B29]/40 border-[#94AFD7]/10 hover:bg-[#111B29]/70 text-[#F4F7FC]"
                  }`}
                >
                  <div className="flex items-center gap-3">
                    <span className="text-[#5B6B80]">{ev.timestamp}</span>
                    <span
                      className={`px-1.5 py-0.5 rounded text-[10px] font-bold ${
                        ev.severity === "CRITICAL"
                          ? "bg-[#FF4567]/20 text-[#FF4567]"
                          : ev.severity === "SUSPICIOUS"
                          ? "bg-[#FFB547]/20 text-[#FFB547]"
                          : "bg-[#19D995]/20 text-[#19D995]"
                      }`}
                    >
                      {ev.severity}
                    </span>
                    <span className="text-[#00D5FF] font-semibold">{ev.protocol}</span>
                    <span>
                      {ev.sourceIp} → {ev.destIp}:{ev.port}
                    </span>
                  </div>

                  <div className="flex items-center gap-3">
                    <span className="text-xs text-[#8795A9] truncate max-w-xs">
                      {ev.message}
                    </span>
                    <span className="font-bold text-[#F4F7FC]">
                      {ev.score.toFixed(3)}
                    </span>
                  </div>
                </div>
              ))
            )}
            <div ref={streamEndRef} />
          </div>

          {/* Jump to Latest Floating Pill */}
          {!autoScroll && (
            <div className="p-2 border-t border-[#94AFD7]/10 bg-[#0D1420] flex justify-center">
              <button
                onClick={() => {
                  setAutoScroll(true);
                  streamEndRef.current?.scrollIntoView({ behavior: "smooth" });
                }}
                className="flex items-center gap-1.5 px-3 py-1 rounded-full bg-[#00D5FF] text-[#05080F] text-xs font-bold shadow-lg"
              >
                <ArrowDown size={13} />
                <span>Jump to latest event</span>
              </button>
            </div>
          )}
        </div>

        {/* Right Col: Live Telemetry Panels */}
        <div className="space-y-6">
          {/* Rate Sparkline */}
          <div className="p-5 rounded-2xl glass-panel space-y-3">
            <div className="flex items-center justify-between">
              <span className="text-xs text-[#8795A9]">Ingestion Rate</span>
              <Activity size={16} className="text-[#00D5FF]" />
            </div>
            <div className="text-2xl font-display font-bold text-[#F4F7FC]">
              {eventsPerSec[eventsPerSec.length - 1]} flows/sec
            </div>
            <div className="pt-2">
              <Sparkline data={eventsPerSec} width={220} height={40} color="#00D5FF" />
            </div>
          </div>

          {/* Severity Counters */}
          <div className="p-5 rounded-2xl glass-panel space-y-3">
            <span className="text-xs text-[#8795A9] block">Session Ingestion Tally</span>
            <div className="space-y-2 font-mono text-xs">
              <div className="flex items-center justify-between p-2 rounded-lg bg-[#111B29]/60">
                <span className="text-[#19D995]">Normal Flows</span>
                <span className="font-bold text-[#F4F7FC]">{severityCounts.normal}</span>
              </div>
              <div className="flex items-center justify-between p-2 rounded-lg bg-[#111B29]/60">
                <span className="text-[#FFB547]">Suspicious Activity</span>
                <span className="font-bold text-[#F4F7FC]">{severityCounts.suspicious}</span>
              </div>
              <div className="flex items-center justify-between p-2 rounded-lg bg-[#111B29]/60">
                <span className="text-[#FF4567]">Flagged Threats</span>
                <span className="font-bold text-[#F4F7FC]">{severityCounts.critical}</span>
              </div>
            </div>
          </div>

          {/* Top Talkers */}
          <div className="p-5 rounded-2xl glass-panel space-y-3 font-mono text-xs">
            <span className="text-xs text-[#8795A9] block">Top Talker Endpoints</span>
            <div className="space-y-2">
              <div className="flex justify-between text-[#8795A9]">
                <span>192.168.10.12</span>
                <span className="text-[#F4F7FC]">312 pkts</span>
              </div>
              <div className="flex justify-between text-[#8795A9]">
                <span>192.168.10.50 (FTP)</span>
                <span className="text-[#FF4567]">89 anomalies</span>
              </div>
              <div className="flex justify-between text-[#8795A9]">
                <span>192.168.10.51 (SSH)</span>
                <span className="text-[#FFB547]">42 alerts</span>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
